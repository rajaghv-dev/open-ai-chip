@router.post("/whatif_list", operation_id="whatif_list", summary="List what-if copies under build/whatif/", response_model=None)
def whatif_list(req: Empty = Empty()) -> dict:
    """The what-if copies (design, tag, changes, state, size) and saved patches under build/whatif/. Read-only."""
    items = []
    for d in sorted(glob.glob(os.path.join(BASE, "*__*"))):
        if not os.path.isdir(d):
            continue
        meta = _json(os.path.join(d, "whatif_meta.json"), {}) or {}
        res = _json(os.path.join(d, "whatif_resources.json"), None)
        state = "not run" if res is None else ("done" if res.get("exit_code") == 0 else "failed")
        srv = _server()
        job = srv.JOBS.jobs.get(meta.get("job_id")) if srv and meta.get("job_id") else None
        if res is None and job is not None and job.state == "running":
            state = "running"
        items.append({"dir": os.path.relpath(d, REPO), "design": meta.get("design"), "tag": meta.get("tag"), "changes": meta.get("changes"),
                      "state": state, "created": meta.get("created"), "sweep_id": meta.get("sweep_id")})
    patches = sorted(os.path.relpath(p, REPO) for p in glob.glob(os.path.join(PATCH_DIR, "*.patch")))
    return {"runs": items, "patches": patches, "base": os.path.relpath(BASE, REPO)}


class CleanReq(BaseModel):
    tag: Optional[str] = Field(None, description="remove build/whatif/*__<tag>/")
    all: Optional[bool] = Field(None, description="true: remove every finished what-if copy and saved patch (running ones are kept)")


@router.post("/whatif_clean", operation_id="whatif_clean", summary="Delete what-if copies (only under build/whatif/)", response_model=None)
def whatif_clean(req: CleanReq) -> dict:
    """Delete one what-if copy by tag, or all finished ones. Only paths inside build/whatif/ are ever removed; a copy whose job is still
    running is kept. designs/ is never touched."""
    if not req.tag and not req.all:
        return {"error": "give a tag or all=true"}
    removed, kept = [], []
    srv = _server()
    for d in sorted(glob.glob(os.path.join(BASE, "*__*"))):
        meta = _json(os.path.join(d, "whatif_meta.json"), {}) or {}
        if req.tag and meta.get("tag") != req.tag:
            continue
        job = srv.JOBS.jobs.get(meta.get("job_id")) if srv and meta.get("job_id") else None
        if job is not None and job.state == "running":
            kept.append(os.path.relpath(d, REPO))
            continue
        real = os.path.realpath(d)
        if not real.startswith(os.path.realpath(BASE) + os.sep):
            continue
        shutil.rmtree(d, ignore_errors=True)
        removed.append(os.path.relpath(d, REPO))
    if req.all and os.path.isdir(PATCH_DIR):
        for p in glob.glob(os.path.join(PATCH_DIR, "*.patch")):
            os.remove(p)
            removed.append(os.path.relpath(p, REPO))
    return {"removed": removed, "kept_running": kept}


