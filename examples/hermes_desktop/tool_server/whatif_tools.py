def _cfg_get(cfg: dict, key: str):
    """(present, value, spelling used in the config) for a canonical key, honouring deprecated spellings."""
    for spelling in [key] + catalog().get(key, {}).get("aliases", []):
        if spelling in cfg:
            return True, cfg[spelling], spelling
    return False, None, key


def effective(design: str, key: str) -> Dict[str, Any]:
    """Current value of a variable for a design: config.json value, else the library default, else the PDK/SCL value that a
    flow resolved (resolved_default). source says which."""
    key = canonical(key)
    cfg = repo.config(design)
    present, v, spelling = _cfg_get(cfg, key)
    if present:
        return {"value": v, "source": "config.json" + ("" if spelling == key else " (as " + spelling + ")"), "spelling": spelling}
    c = catalog().get(key, {})
    if c.get("resolved_default") is not None:
        return {"value": c["resolved_default"], "source": "default (resolved by a flow run; PDK/library value)", "spelling": key}
    d = c.get("default")
    if d is not None:
        try:
            v = ast.literal_eval(d)
        except (ValueError, SyntaxError):
            v = d
        return {"value": v, "source": "default (LibreLane 3.0.2)", "spelling": key}
    return {"value": None, "source": "unset (derived at run time)" if c else "unknown", "spelling": key}


def _is_num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _literal_options(tp: str) -> Optional[List[str]]:
    m = re.search(r"Literal\[(.*)\]", tp)
    return re.findall(r"'([^']*)'", m.group(1)) if m else None


def coerce(tp: str, v: Any):
    """Accept '20' / 'true' strings from a model; returns (value, error)."""
    inner = re.sub(r"^Optional\[(.*)\]$", r"\1", tp)
    if v is None:
        return (None, None) if tp.startswith("Optional") else (None, "null is not allowed for %s" % tp)
    if inner == "bool":
        if isinstance(v, bool):
            return v, None
        if isinstance(v, str) and v.strip().lower() in ("true", "false"):
            return v.strip().lower() == "true", None
        return v, "expected true or false"
    if inner == "int":
        if isinstance(v, bool):
            return v, "expected an integer"
        if isinstance(v, (int, float)) and float(v) == int(v):
            return int(v), None
        if isinstance(v, str) and re.fullmatch(r"-?\d+", v.strip()):
            return int(v), None
        return v, "expected an integer"
    if inner in ("decimal.Decimal", "float"):
        if _is_num(v):
            return v, None
        if isinstance(v, str) and re.fullmatch(r"-?\d+(\.\d+)?", v.strip()):
            return float(v) if "." in v else int(v), None
        return v, "expected a number"
    if inner.startswith("Literal"):
        opts = _literal_options(inner) or []
        if isinstance(v, str) and v in opts:
            return v, None
        return v, "expected one of: " + ", ".join(opts)
    if inner == "str":
        return (v, None) if isinstance(v, str) else (v, "expected a string")
    if inner.startswith("Tuple") or inner.startswith("List"):
        if isinstance(v, list):
            return v, None
        return v, "expected a list"
    return v, None


def check_key(design: str, key: str, value: Any) -> Dict[str, Any]:
    """One key against the HARD RULES and the variable catalog. Returns {key, canonical, status, rule, reason, current, value, notes[]}."""
    r: Dict[str, Any] = {"key": key, "status": "allowed", "value": value, "notes": []}

    def block(rule: str, why: str):
        r.update(status="blocked", rule=rule, rule_text=RULE_TEXT[rule], reason=why)
        return r

    ck = canonical(key)
    r["canonical"] = ck
    if ck != key:
        r["notes"].append("%s is a deprecated alias of %s in LibreLane 3.0.2" % (key, ck))
    if key == "DISABLE_LVS" or LVS_NAMES.search(ck):
        return block("R2-LVS", "%s touches LVS; LVS may not be disabled, skipped or weakened." % key)
    if ck not in catalog():
        return block("R9-UNKNOWN", "%s is not a LibreLane 3.0.2 variable." % key)
    cur = effective(design, ck) if os.path.isfile(repo.config_path(design)) else {"value": None, "source": "unknown", "spelling": ck}
    r["current"] = cur["value"]
    r["current_source"] = cur["source"]
    tp = catalog()[ck]["type"]
    val, err = coerce(tp, value)
    if err:
        return block("R10-TYPE", "%s = %r: %s (type %s)." % (ck, value, err, tp))
    r["value"] = val
    # identity / file / tool-setup keys
    if ck in NOT_TUNABLE or any(ck.startswith(p) for p in NOT_TUNABLE_PREFIX) or "Path" in tp:
        if CORNER_KEYS.search(ck):
            return block("R5-WEAKEN", "%s selects timing corners; changing the corner set can hide a violation." % ck)
        if ck.startswith(("MAGIC", "KLAYOUT", "RCX_", "STA_", "LINTER")) or ck.startswith("LVS"):
            return block("R5-WEAKEN", "%s is a signoff tool setting (DRC, extraction, STA, lint); it may not be changed from an agent." % ck)
        return block("R8-DESIGN-FILE", "%s is a design-owned identity, file or net setting." % ck)
    if CORNER_KEYS.search(ck):
        return block("R5-WEAKEN", "%s selects timing corners; changing the corner set can hide a violation." % ck)
    # wrapper geometry
    if is_wrapper(design) and GEOMETRY.match(ck):
        return block("R6-GEOMETRY", "%s is part of the fixed Caravel wrapper geometry/pins of %s." % (ck, design))
    if ck == "SYNTH_STRATEGY" and str(val).upper().startswith("DELAY"):
        return block("R3-DELAY", "SYNTH_STRATEGY %r is a DELAY strategy." % val)
    if ck == "ERROR_ON_SYNTH_CHECKS" and val is False:
        return block("R4-SYNTH-CHECKS", "ERROR_ON_SYNTH_CHECKS must stay true.")
    if ck == "SYNTH_ELABORATE_ONLY" and val is True:
        return block("R7-ELABORATE", "SYNTH_ELABORATE_ONLY true would skip logic mapping for %s." % design)
    if ck.startswith("ERROR_ON_") and val is False and ck != "ERROR_ON_LINTER_WARNINGS" and cur["value"] is not False:
        return block("R5-WEAKEN", "%s false turns a signoff check from an error into a warning." % ck)
    if ck in RUN_OFF_BLOCKED and val is False and cur["value"] is not False:
        return block("R5-WEAKEN", "%s false skips a signoff, repair or check step that is on for %s." % (ck, design))
    if ck == "MAGIC_DRC_USE_GDS" and val is False:
        return block("R5-WEAKEN", "MAGIC_DRC_USE_GDS false changes the DRC input.")
    if ck.endswith("_ALLOW_SETUP_VIOS") and val is True:
        return block("R11-MARGIN", "%s true lets hold repair create setup violations." % ck)
    if ck.endswith("_SLACK_MARGIN") and _is_num(val) and val < 0:
        return block("R11-MARGIN", "%s = %s is a negative slack margin: repair would stop with negative slack left." % (ck, val))
    if ck in TIGHTEN_ONLY and _is_num(val):
        cv = cur["value"]
        if ck == "CLOCK_PERIOD":
            cv = cv if _is_num(cv) else 25
            if val <= CLOCK_FLOOR_NS:
                return block("R10-TYPE", "CLOCK_PERIOD must be positive.")
            if val > cv:
                return block("R1-CLOCK", "CLOCK_PERIOD %s ns is longer than the current %s ns (loosening); only a shorter period is allowed." % (val, cv))
            r["notes"].append("tightens the clock from %s ns to %s ns (%.0f MHz); setup slack will shrink" % (cv, val, 1000.0 / val))
        elif ck == "MAX_TRANSITION_CONSTRAINT":
            cv = cv if _is_num(cv) else 0.75
            if val > cv:
                return block("R1-SLEW", "MAX_TRANSITION_CONSTRAINT %s ns is above the current %s ns (loosening); only a lower value is allowed." % (val, cv))
            r["notes"].append("tightens the slew limit from %s ns to %s ns; expect more repair work and more violations to read" % (cv, val))
        elif _is_num(cv):
            down = TIGHTEN_ONLY[ck] == "down"
            if (down and val > cv) or ((not down) and val < cv):
                return block("R1-TIGHTEN", "%s = %s moves away from the tight direction (current %s; allowed: %s)." % (
                    ck, val, cv, "lower" if down else "higher"))
    # warnings (allowed, but said)
    if ck in ("DESIGN_REPAIR_MAX_SLEW_PCT", "GRT_DESIGN_REPAIR_MAX_SLEW_PCT") and _is_num(val) and val > 40:
        r["notes"].append("WARNING: slew margins above 40 percent ran the 8 GB container out of memory in this repo (70 percent on tiny_ai_core; 40 percent on the 80 and 120 um designs); the run is capped by FLOW_TIMEOUT")
    if ck == "DIE_AREA" and isinstance(val, list) and len(val) == 4:
        r["notes"].append("the die sets utilisation; above about 80 percent placement or repair failed in this repo, below 30 percent area is wasted")
    if ck == "PL_TARGET_DENSITY_PCT" and _is_num(val) and (val <= 0 or val > 100):
        return block("R10-TYPE", "PL_TARGET_DENSITY_PCT is a percent between 1 and 100.")
    if ck.startswith("SYNTH_ABC_DFF") and val is True:
        r["notes"].append("flip-flops through ABC can merge registers; check_signoff.py then fails on 'logic lost' unless an allowance with a RTL-verifiable reason exists")
    if is_wrapper(design):
        r["notes"].append("%s is a wrapper/macro-bearing design: propose_change works, whatif_run does not (needs macro views)" % design)
    return r


def rule_of(key: str) -> str:
    """The HARD RULE that applies to a key, in words (for param_info)."""
    ck = canonical(key)
    if ck == "CLOCK_PERIOD":
        return RULE_TEXT["R1-CLOCK"]
    if ck == "MAX_TRANSITION_CONSTRAINT":
        return RULE_TEXT["R1-SLEW"]
    if ck in TIGHTEN_ONLY:
        return RULE_TEXT["R1-TIGHTEN"] + " Direction: %s." % ("lower is tighter" if TIGHTEN_ONLY[ck] == "down" else "higher is tighter")
    if ck == "SYNTH_STRATEGY":
        return RULE_TEXT["R3-DELAY"]
    if ck == "ERROR_ON_SYNTH_CHECKS":
        return RULE_TEXT["R4-SYNTH-CHECKS"]
    if ck == "SYNTH_ELABORATE_ONLY":
        return RULE_TEXT["R7-ELABORATE"]
    if LVS_NAMES.search(ck):
        return RULE_TEXT["R2-LVS"]
    if ck in RUN_OFF_BLOCKED or ck.startswith("ERROR_ON_") or CORNER_KEYS.search(ck):
        return RULE_TEXT["R5-WEAKEN"] + " (setting it to false / changing the corners is blocked)"
    if ck.endswith("_SLACK_MARGIN") or ck.endswith("_ALLOW_SETUP_VIOS"):
        return RULE_TEXT["R11-MARGIN"]
    if ck in NOT_TUNABLE or any(ck.startswith(p) for p in NOT_TUNABLE_PREFIX):
        return RULE_TEXT["R8-DESIGN-FILE"]
    if GEOMETRY.match(ck):
        return "Free on a macro or engine copy; blocked on the Caravel wrappers (" + RULE_TEXT["R6-GEOMETRY"] + ")"
    return "No special rule beyond the global ones (never loosen CLOCK_PERIOD / MAX_TRANSITION_CONSTRAINT, never DISABLE_LVS, no DELAY, keep ERROR_ON_SYNTH_CHECKS true)."


