class SweepReq(BaseModel):
    design: Optional[str] = Field(None, description="design directory name, e.g. vision_block", examples=["vision_block"])
    key: Optional[str] = Field(None, description="the one variable to sweep, e.g. PL_TARGET_DENSITY_PCT", examples=["PL_TARGET_DENSITY_PCT"])
    values: Optional[List[Any]] = Field(None, description="2 to 6 values; each is checked against the HARD RULES, blocked ones are dropped and listed",
                                        examples=[[50, 60, 70]])
    confirm_id: Optional[str] = Field(None, description="SECOND call only: the confirm_id from the first reply, after the USER wrote 'yes, run <confirm_id>'")


@router.post("/whatif_sweep", operation_id="whatif_sweep", summary="Run what-if flows for several values of one setting, one after the other (needs user confirmation)", response_model=None)
def whatif_sweep(req: SweepReq) -> dict:
    """Sweep one setting over 2..6 values: one what-if copy per value, run sequentially inside ONE job (one physical flow at a time).
    TWO STEPS like whatif_run: the first call returns the plan and a confirm_id; start only after the user says 'yes, run <confirm_id>'.
    Then poll job_status and call whatif_result {sweep_id}."""
    confirmed = None
    if req.confirm_id:
        got, resp = _gate("whatif", {}, "", "", req.confirm_id)
        if resp:
            return resp
        payload, confirmed = got
        design, key, values = payload["design"], payload["key"], payload["values"]
    else:
        design, key, values = req.design, req.key, req.values
    err = _check_design(design)
    if err:
        return {"error": err}
    if not key or not isinstance(values, list) or not (2 <= len(values) <= MAX_SWEEP):
        return {"error": "give key and 2..%d values" % MAX_SWEEP}
    err = _supported(design)
    if err:
        return {"error": err}
    runs, blocked = [], []
    for v in values:
        ev = evaluate(design, {key: v})
        if ev["blocked"]:
            blocked.append({"value": v, "rule": ev["blocked"][0]["rule"], "reason": ev["blocked"][0]["reason"]})
        else:
            runs.append(v)
    if not runs:
        return {"error": "every value is blocked by the HARD RULES; nothing was started", "blocked": blocked}
    busy = docker_busy()
    if busy:
        return {"error": "a flow container is already running (%s); only one physical flow at a time" % busy}
    cmd_preview = "python3 examples/hermes_desktop/tool_server/whatif_tools.py sweep <manifest> (%d runs of scripts/flow/whatif_flow.sh in sequence)" % len(runs)
    payload = {"design": design, "key": key, "values": values}
    plan = {"design": design, "key": canonical(key), "values": runs, "blocked_values": blocked, "runs": len(runs),
            "expected": "%d runs, each %s" % (len(runs), _expected_minutes(design)), "designs_untouched": True}
    if not confirmed and not (_server() and _server()._no_confirm()):
        _, resp = _gate("whatif", payload, cmd_preview, "what-if sweep of %s over %s on %s (%d sequential flows)" % (key, runs, design, len(runs)), None)
        if resp:
            resp["plan"] = plan
            return resp
    sid = "sw" + time.strftime("%m%d%H%M%S")
    manifest = {"sweep_id": sid, "design": design, "key": canonical(key), "runs": []}
    for i, v in enumerate(runs):
        tag = "%s-%d" % (sid, i + 1)
        prep = prepare_copy(design, tag, {canonical(key): coerce(catalog()[canonical(key)]["type"], v)[0]})
        if prep["missing"]:
            return {"error": "a dir:: path of the copy does not resolve: %s" % prep["missing"]}
        _write_meta(prep["dir"], {"design": design, "tag": tag, "changes": {canonical(key): v}, "sweep_id": sid,
                                  "created": datetime.datetime.now().isoformat(timespec="seconds")})
        manifest["runs"].append({"tag": tag, "value": v, "dir": os.path.relpath(prep["dir"], REPO)})
    os.makedirs(SWEEP_DIR, exist_ok=True)
    mpath = os.path.join(SWEEP_DIR, sid + ".json")
    json.dump(manifest, open(mpath, "w"), indent=1)
    cmd = [sys.executable, os.path.join("examples", "hermes_desktop", "tool_server", "whatif_tools.py"), "sweep", os.path.relpath(mpath, REPO)]
    job, err = _start_job(cmd, "whatif sweep %s %s" % (design, key), confirmed)
    if err:
        for r in manifest["runs"]:
            shutil.rmtree(os.path.join(REPO, r["dir"]), ignore_errors=True)
        return {"error": err}
    for r in manifest["runs"]:
        meta_p = os.path.join(REPO, r["dir"], "whatif_meta.json")
        m = _json(meta_p, {})
        m["job_id"] = job.id
        json.dump(m, open(meta_p, "w"), indent=1)
    return {"job_id": job.id, "sweep_id": sid, "state": job.state, "runs": manifest["runs"], "blocked_values": blocked,
            "log": os.path.relpath(job.log, REPO), "next": "poll job_status; then whatif_result {sweep_id: %s}" % sid}


def sweep_result(sid: str) -> Dict[str, Any]:
    if not re.fullmatch(r"sw\d{10}", sid or ""):
        return {"error": "bad sweep_id %r" % sid}
    man = _json(os.path.join(SWEEP_DIR, sid + ".json"), None)
    if not man:
        return {"error": "unknown sweep_id %s" % sid}
    ana = _analysis()
    c = _committed(man["design"])
    ko = ana.key_numbers(c["metrics"])
    rows, details = [], []
    for r in man["runs"]:
        d = os.path.join(REPO, r["dir"])
        res = _json(os.path.join(d, "whatif_resources.json"), None)
        mp = _run_metrics(d, r["tag"])
        if res is None:
            rows.append([r["value"], "not finished", "", "", "", "", "", ""])
            continue
        if res.get("exit_code") != 0 or not mp:
            rows.append([r["value"], "FAILED (exit %s)" % res.get("exit_code"), "", "", "", "", "", res.get("wall_s_total")])
            continue
        kn = ana.key_numbers(_json(mp, {}))
        viol = ana.violations(_json(mp, {}))
        sw, hw = kn["setup_worst"] or {}, kn["hold_worst"] or {}
        rows.append([r["value"], "clean" if not viol else "FAILS: %s" % viol[0], kn["stdcells"], kn["utilisation_pct"], sw.get("slack_ns"), hw.get("slack_ns"),
                     kn["max_slew_violations"], res.get("wall_s_total")])
        details.append(r["tag"])
    so, ho = ko["setup_worst"] or {}, ko["hold_worst"] or {}
    rows.append(["committed", "clean", ko["stdcells"], ko["utilisation_pct"], so.get("slack_ns"), ho.get("slack_ns"), ko["max_slew_violations"], c["wall_s"]])
    head = [man["key"], "result", "std cells", "util %", "setup ws ns", "hold ws ns", "slew viol", "wall s"]
    return {"sweep_id": sid, "design": man["design"], "key": man["key"], "markdown": md_table(head, rows), "rows": rows, "head": head,
            "tags": details, "designs_touched": False}


