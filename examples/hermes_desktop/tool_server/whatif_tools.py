@router.post("/param_info", operation_id="param_info", summary="Explain a synthesis / timing / OpenROAD setting and show its current value", response_model=None)
def param_info(req: ParamReq) -> dict:
    """With `key`: current value (and where it comes from), library default, engine, meaning, safe range, the symptom it fixes, how to verify,
    the HARD RULE that applies, the design's own //KEY comment, and the docs link. Without `key`: the tunable keys grouped by engine with their
    current values (set in config.json or default). Read-only."""
    err = _check_design(req.design)
    if err:
        return {"error": err}
    cat = catalog()
    if not cat:
        return {"error": "whatif_keys.json missing; run python3 scripts/flow/gen_whatif_keys.py"}
    if req.key:
        ck = canonical(req.key)
        if ck not in cat:
            near = [k for k in cat if req.key.upper() in k][:8]
            return {"error": "%s is not a LibreLane 3.0.2 variable" % req.key, "rule": RULE_TEXT["R9-UNKNOWN"], "did_you_mean": near}
        c, n, cur = cat[ck], notes().get(ck, {}), effective(req.design, ck)
        out = {"design": req.design, "key": ck, "alias_of": req.key if ck != req.key else None, "aliases": c.get("aliases", []),
               "engine": engine_of(ck), "type": c["type"], "unit": c.get("units"),
               "current": {"value": cur["value"], "source": cur["source"]},
               "default": c.get("default") if c.get("default") is not None else c.get("resolved_default"),
               "meaning": n.get("meaning") or c["desc"], "librelane_description": c["desc"],
               "safe_range": n.get("safe"), "symptom_it_fixes": n.get("symptom"), "verify_with": n.get("verify"),
               "repo_choice": n.get("repo"), "design_comment": _comment_for(req.design, ck),
               "rule": rule_of(ck), "doc": n.get("doc") or "docs/OPENROAD_ENGINES.md",
               "skills": SKILLS, "used_by_steps": c.get("sources", [])}
        # would a value be allowed? show the current value's check as a self-test of the rule
        return {k: v for k, v in out.items() if v is not None}
    groups: Dict[str, List[dict]] = {}
    for k in sorted(notes()):
        if k not in cat or (req.engine and engine_of(k) != req.engine):
            continue
        cur = effective(req.design, k)
        groups.setdefault(engine_of(k), []).append({"key": k, "value": cur["value"], "set_in_config": cur["source"].startswith("config.json")})
    return {"design": req.design, "engines": groups, "count": sum(len(v) for v in groups.values()),
            "note": "call param_info with a key for meaning, safe range and rule; 'set_in_config' false means the default applies",
            "skills": SKILLS}


# ---------------------------------------------------------------- patch text
def _config_text(design: str) -> str:
    t = open(repo.config_path(design), encoding="utf-8").read()
    return t if t.endswith("\n") else t + "\n"


def apply_changes(cfg: dict, changes: Dict[str, Any]) -> dict:
    """A copy of cfg with the (already validated and coerced) changes; an existing deprecated spelling is changed in place so the
    config never carries both names."""
    out = copy.deepcopy(cfg)
    for k, v in changes.items():
        ck = canonical(k)
        present, _, spelling = _cfg_get(out, ck)
        out[spelling if present else ck] = v
    return out


def make_patch(design: str, changes: Dict[str, Any]) -> str:
    old_text = _config_text(design)
    cfg = json.loads(old_text)
    new_text = json.dumps(apply_changes(cfg, changes), indent=4) + "\n"
    old_norm = json.dumps(cfg, indent=4) + "\n"
    rel = "designs/%s/config.json" % design
    diff = difflib.unified_diff(old_norm.splitlines(True), new_text.splitlines(True), "a/" + rel, "b/" + rel)
    return "".join(diff)


class ChangeReq(BaseModel):
    design: str = Field(..., description="design directory name, e.g. vision_block", examples=["vision_block"])
    changes: Dict[str, Any] = Field(..., description="{LibreLane_KEY: value}, e.g. {\"CLOCK_PERIOD\": 20, \"PL_TARGET_DENSITY_PCT\": 70}",
                                    examples=[{"CLOCK_PERIOD": 20}])


def evaluate(design: str, changes: Dict[str, Any]) -> Dict[str, Any]:
    per = [check_key(design, k, v) for k, v in changes.items()]
    allowed = {canonical(p["key"]): p["value"] for p in per if p["status"] == "allowed"}
    return {"per_key": per, "allowed": allowed, "blocked": [p for p in per if p["status"] == "blocked"]}


@router.post("/propose_change", operation_id="propose_change", summary="Check proposed setting changes against the HARD RULES and make a patch text", response_model=None)
def propose_change(req: ChangeReq) -> dict:
    """Validate {KEY: value} changes for a design: each key is `allowed` or `blocked` with the rule and reason (CLOCK_PERIOD and
    MAX_TRANSITION_CONSTRAINT may only be tightened; no DISABLE_LVS; no SYNTH_STRATEGY DELAY; ERROR_ON_SYNTH_CHECKS stays true; no weaker
    DRC/LVS/timing/precheck settings; wrapper geometry is fixed; unknown keys refused). Returns a unified diff of config.json as PATCH
    TEXT (saved under build/whatif/patches/). NEVER applies it: the owner applies a patch by hand if wanted."""
    err = _check_design(req.design)
    if err:
        return {"error": err}
    if not req.changes:
        return {"error": "changes is empty"}
    ev = evaluate(req.design, req.changes)
    patch, saved = "", None
    if ev["allowed"]:
        patch = make_patch(req.design, ev["allowed"])
        os.makedirs(PATCH_DIR, exist_ok=True)
        name = "%s_%s_%s.patch" % (req.design, time.strftime("%Y%m%d_%H%M%S"), secrets.token_hex(2))
        saved = os.path.join(PATCH_DIR, name)
        with open(saved, "w", encoding="utf-8") as f:
            f.write(patch)
    return {"design": req.design, "verdict": "all allowed" if not ev["blocked"] else ("all blocked" if not ev["allowed"] else "partly blocked"),
            "keys": [{k: v for k, v in p.items() if k in ("key", "canonical", "status", "value", "current", "rule", "rule_text", "reason", "notes")}
                     for p in ev["per_key"]],
            "patch_text": patch, "patch_file": os.path.relpath(saved, REPO) if saved else None, "applied": False,
            "note": "Nothing was applied and designs/%s/ is untouched. The patch covers the allowed keys only. To see the effect, call whatif_run "
                    "(runs on a copy under build/whatif/). Editing config.json makes the committed run stale (find_reusable_run.py), so only the "
                    "owner applies a patch." % req.design}


# ---------------------------------------------------------------- the copy
def _dirs_rewrite(cfg_val, src_cfg_dir: str, dst_dir: str, src_design_dir: str, keep: List[str]):
    """Rewrite dir:: paths for the copy. A target inside the copied part of the design directory stays as it is (the copy holds it);
    every other target gets a path relative to the copy (dir:: only takes relative paths, and `..` means something else after the move)."""
    if isinstance(cfg_val, str) and cfg_val.startswith("dir::"):
        tgt = os.path.normpath(os.path.join(src_cfg_dir, cfg_val[5:]))
        rel_in = os.path.relpath(tgt, src_design_dir)
        if not rel_in.startswith("..") and os.path.exists(os.path.join(dst_dir, rel_in)):
            return cfg_val
        return "dir::" + os.path.relpath(tgt, dst_dir)
    if isinstance(cfg_val, list):
        return [_dirs_rewrite(x, src_cfg_dir, dst_dir, src_design_dir, keep) for x in cfg_val]
    if isinstance(cfg_val, dict):
        return {k: _dirs_rewrite(x, src_cfg_dir, dst_dir, src_design_dir, keep) for k, x in cfg_val.items()}
    return cfg_val


def _walk_dirs(v):
    if isinstance(v, str) and v.startswith("dir::"):
        yield v[5:]
    elif isinstance(v, list):
        for x in v:
            yield from _walk_dirs(x)
    elif isinstance(v, dict):
        for x in v.values():
            yield from _walk_dirs(x)


def whatif_dir(design: str, tag: str) -> str:
    return os.path.join(BASE, "%s__%s" % (design, tag))


def prepare_copy(design: str, tag: str, changes: Dict[str, Any], base: Optional[str] = None) -> Dict[str, Any]:
    """Copy designs/<d>/ (without runs/, output/, tb/, *.md) to build/whatif/<d>__<tag>/, rewrite every dir:: path of config.json so it
    still resolves from there, apply the changes. Never writes below designs/. Returns {dir, missing, config}."""
    base = base or BASE
    if not TAG_RE.match(tag):
        raise ValueError("bad tag %r" % tag)
    src = os.path.join(REPO, "designs", design)
    dst = os.path.join(base, "%s__%s" % (design, tag))
    real = os.path.realpath(dst)
    if not real.startswith(os.path.realpath(base) + os.sep):
        raise ValueError("copy path escapes build/whatif")
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("runs", "output", "tb", "*.md", "__pycache__", ".DS_Store"))
    cfg = json.load(open(os.path.join(src, "config.json")))
    cfg = {k: _dirs_rewrite(v, src, dst, src, []) for k, v in cfg.items()}
    cfg = apply_changes(cfg, changes)
    with open(os.path.join(dst, "config.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=4)
        f.write("\n")
    missing = [p for p in _walk_dirs(cfg) if not os.path.exists(os.path.normpath(os.path.join(dst, p)))]
    return {"dir": dst, "missing": missing, "config": cfg}


# ---------------------------------------------------------------- server plumbing (gate, lock, jobs)
def _server():
    if SERVER_HOOK:
        return SERVER_HOOK()
    for name in ("tool_server", "__main__"):
        m = sys.modules.get(name)
        if m is not None and hasattr(m, "JOBS") and hasattr(m, "_issue_confirm"):
            return m
    return None


def _docker_env() -> Dict[str, str]:
    return repo.docker_env(dict(os.environ))


def docker_busy() -> Optional[str]:
    """Name of a running LibreLane/flow container (another session may be running a flow), else None. Docker unreachable: None."""
    if DOCKER_BUSY_HOOK:
        return DOCKER_BUSY_HOOK()
    try:
        env = dict(os.environ)
        env.update(_docker_env())
        r = subprocess.run(["docker", "ps", "--format", "{{.Names}}|{{.Command}}"], capture_output=True, text=True, timeout=15, env=env)
    except (OSError, subprocess.SubprocessError):
        return None
    for line in r.stdout.splitlines():
        name, _, command = line.partition("|")
        # a flow runs `python3 -m librelane ...`; GUI containers (magic, openroad viewers) of the same image are not flows
        if name.startswith(("oac_cap_", "oac_whatif_")) or "-m librelane" in command or "librelane " in command:
            return name
    return None


