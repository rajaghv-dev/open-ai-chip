def _check_design(d: Any) -> Optional[str]:
    if not isinstance(d, str) or d not in repo.design_dirs():
        return "unknown design %r; valid: %s" % (d, " ".join(repo.design_dirs()))
    return None


def _comment_for(design: str, key: str) -> Optional[Dict[str, str]]:
    """The design's own //KEY comment about this variable (the reasoning behind the committed value)."""
    cfg = repo.config(design)
    ck = canonical(key)
    cands = ["//" + ck] + ["//" + a for a in catalog().get(ck, {}).get("aliases", [])]
    if "SLEW" in ck:
        cands.append("//SLEW")
    if ck in ("DIE_AREA", "CORE_AREA") or ck.startswith("FP_"):
        cands.append("//DIE_AREA")
    for c in cands:
        if c in cfg:
            return {"key": c, "text": cfg[c] if isinstance(cfg[c], str) else json.dumps(cfg[c])}
    return None


def _fmt(v) -> str:
    return json.dumps(v) if not isinstance(v, str) else v


