def compare(design: str, new: dict, old: dict, new_res: dict, old_wall, old_mem) -> Dict[str, Any]:
    """Code-built comparison table and verdict (new = the what-if metrics, old = committed). Pure function of two metrics dicts."""
    ana = _analysis()
    kn, ko = ana.key_numbers(new), ana.key_numbers(old)

    rows = []

    def row(name, a, b, delta=""):
        rows.append({"metric": name, "whatif": a, "committed": b, "delta": delta})

    row("std cells", kn["stdcells"], ko["stdcells"], _delta(kn["stdcells"], ko["stdcells"], 0, True))
    row("flip-flops", kn["flip_flops"], ko["flip_flops"], _delta(kn["flip_flops"], ko["flip_flops"], 0))
    row("die (um)", kn["die_um"], ko["die_um"])
    row("utilisation %", kn["utilisation_pct"], ko["utilisation_pct"], _delta(kn["utilisation_pct"], ko["utilisation_pct"], 2))
    sw, so = (kn["setup_worst"] or {}), (ko["setup_worst"] or {})
    hw, ho = (kn["hold_worst"] or {}), (ko["hold_worst"] or {})
    row("setup worst slack ns (%s)" % sw.get("corner", "?"), sw.get("slack_ns"), so.get("slack_ns"), _delta(sw.get("slack_ns"), so.get("slack_ns"), 3))
    row("hold worst slack ns (%s)" % hw.get("corner", "?"), hw.get("slack_ns"), ho.get("slack_ns"), _delta(hw.get("slack_ns"), ho.get("slack_ns"), 3))
    for label, a, b in (("DRC magic", kn["drc"]["magic"], ko["drc"]["magic"]), ("DRC klayout", kn["drc"]["klayout"], ko["drc"]["klayout"]),
                        ("DRC route", kn["drc"]["route"], ko["drc"]["route"]), ("LVS errors", kn["lvs_errors"], ko["lvs_errors"]),
                        ("XOR differences", kn["xor_differences"], ko["xor_differences"]),
                        ("antenna violating nets", kn["antenna"]["violating_nets"], ko["antenna"]["violating_nets"]),
                        ("max slew violations", kn["max_slew_violations"], ko["max_slew_violations"]),
                        ("max cap violations", kn["max_cap_violations"], ko["max_cap_violations"]),
                        ("max fanout violations", kn["max_fanout_violations"], ko["max_fanout_violations"])):
        row(label, a, b, _delta(a, b, 0))
    row("power total mW", kn["power_total_mW"], ko["power_total_mW"], _delta(kn["power_total_mW"], ko["power_total_mW"], 4))
    row("flow wall time s", new_res.get("wall_s_total"), old_wall, _delta(new_res.get("wall_s_total"), old_wall, 0))
    row("container peak memory GB", new_res.get("container_peak_mem_gb"), old_mem, _delta(new_res.get("container_peak_mem_gb"), old_mem, 3))
    corners = []
    for c in CORNERS:
        corners.append({"corner": c, "setup_whatif": _g(new, "timing__setup__ws__corner:" + c), "setup_committed": _g(old, "timing__setup__ws__corner:" + c),
                        "hold_whatif": _g(new, "timing__hold__ws__corner:" + c), "hold_committed": _g(old, "timing__hold__ws__corner:" + c)})
    viol = ana.violations(new)
    parts = []
    if viol:
        parts.append("FAILS signoff: " + "; ".join(viol[:4]))
    else:
        parts.append("CLEAN: no DRC, LVS, XOR, antenna, slew/cap or negative-slack violation in the what-if metrics")
    if _num(kn["stdcells"]) and _num(ko["stdcells"]):
        parts.append("cells %s" % _delta(kn["stdcells"], ko["stdcells"], 0, True))
    if _num(sw.get("slack_ns")) and _num(so.get("slack_ns")):
        parts.append("setup slack %s ns" % _delta(sw.get("slack_ns"), so.get("slack_ns"), 2))
    if _num(hw.get("slack_ns")) and _num(ho.get("slack_ns")):
        parts.append("hold slack %s ns" % _delta(hw.get("slack_ns"), ho.get("slack_ns"), 3))
    return {"table": rows, "corners": corners, "violations": viol, "verdict": "; ".join(parts), "clean": not viol}


def md_table(head: List[str], rows: List[List[Any]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join("" if c is None else str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def result_of(d: str) -> Dict[str, Any]:
    meta = _json(os.path.join(d, "whatif_meta.json"), {}) or {}
    design, tag = meta.get("design"), meta.get("tag")
    out: Dict[str, Any] = {"design": design, "tag": tag, "changes": meta.get("changes"), "dir": os.path.relpath(d, REPO), "job_id": meta.get("job_id")}
    res = _json(os.path.join(d, "whatif_resources.json"), None)
    mpath = _run_metrics(d, tag) if tag else None
    srv = _server()
    job = srv.JOBS.jobs.get(meta.get("job_id")) if srv and meta.get("job_id") else None
    if res is None and job is not None and job.state == "running":
        out.update(state="running", say="the what-if flow is still running; poll job_status %s and call whatif_result again" % job.id)
        return out
    if res is None:
        out.update(state="no result", say="no whatif_resources.json: the run did not finish (job lost or cancelled); whatif_clean it or run again")
        return out
    out["flow_exit_code"] = res.get("exit_code")
    if res.get("exit_code") != 0 or not mpath:
        log = _tail(os.path.join(d, "runs", tag, "flow.log"), 12) if tag else []
        out.update(state="failed", say="the flow failed (exit %s) after %s s; last log lines below. The committed run is untouched." % (
            res.get("exit_code"), res.get("wall_s_total")), log_tail=log)
        return out
    new = _json(mpath, {}) or {}
    c = _committed(design)
    cmp_ = compare(design, new, c["metrics"], res, c["wall_s"], c["mem_gb"])
    sign = os.path.join(d, "signoff.txt")
    out.update(state="done", **cmp_)
    out["signoff_check"] = _tail(sign, 8) if os.path.isfile(sign) else None
    out["markdown"] = md_table(["metric", "what-if", "committed", "delta"], [[r["metric"], r["whatif"], r["committed"], r["delta"]] for r in cmp_["table"]]) + \
        "\n\n" + md_table(["corner", "setup what-if", "setup committed", "hold what-if", "hold committed"],
                          [[c_["corner"], c_["setup_whatif"], c_["setup_committed"], c_["hold_whatif"], c_["hold_committed"]] for c_ in cmp_["corners"]])
    out["committed_run_still_current"] = _committed_current(design)
    out["designs_touched"] = False
    return out


def _tail(path: str, n: int) -> List[str]:
    try:
        with open(path, errors="replace") as f:
            return [l.rstrip("\n") for l in f.readlines()[-n:]]
    except OSError:
        return []


