def _sweep_main(manifest_path: str) -> int:
    man = json.load(open(manifest_path))
    rc_all = 0
    for r in man["runs"]:
        print("=== sweep %s: %s = %s (%s) ===" % (man["sweep_id"], man["key"], r["value"], r["tag"]), flush=True)
        rc = subprocess.call(["bash", "scripts/flow/whatif_flow.sh", "--dir", r["dir"], "--design", man["design"], "--tag", r["tag"]], cwd=REPO)
        rc_all = rc_all or rc
    return rc_all


def _cli_prepare(design: str, tag: str, pairs: List[str]) -> int:
    """Terminal use (Claude Code): make the copy build/whatif/<design>__<tag>/ with the rules applied; run it with scripts/flow/whatif_flow.sh."""
    err = _check_design(design) or _supported(design)
    if err or not TAG_RE.match(tag):
        print(err or "bad tag %r" % tag)
        return 2
    changes: Dict[str, Any] = {}
    for p in pairs:
        k, _, v = p.partition("=")
        try:
            changes[k] = json.loads(v)
        except ValueError:
            changes[k] = v
    ev = evaluate(design, changes) if changes else {"allowed": {}, "blocked": []}
    for b in ev["blocked"]:
        print("BLOCKED %s: [%s] %s" % (b["key"], b["rule"], b["reason"]))
    if ev["blocked"]:
        return 3
    if os.path.exists(whatif_dir(design, tag)):
        print("build/whatif/%s__%s exists" % (design, tag))
        return 2
    prep = prepare_copy(design, tag, ev["allowed"])
    _write_meta(prep["dir"], {"design": design, "tag": tag, "changes": ev["allowed"], "created": datetime.datetime.now().isoformat(timespec="seconds")})
    print("copy: %s (missing dir:: targets: %s)" % (os.path.relpath(prep["dir"], REPO), prep["missing"] or "none"))
    print("run:  bash scripts/flow/whatif_flow.sh --dir %s --design %s --tag %s" % (os.path.relpath(prep["dir"], REPO), design, tag))
    return 0


